export function getPublishedServices(): Service[] {
  return INITIAL_SERVICES.filter(
    (service) => service.publicationStatus === "published" && service.allowIndexing,
  ).map(enrichService);
}

export function getServiceBySlug(slug: string): Service | undefined {
  const service = INITIAL_SERVICES.find((entry) => entry.slug === slug);
  return service ? enrichService(service) : undefined;
}

export function getServiceById(id: string): Service | undefined {
  const service = INITIAL_SERVICES.find((entry) => entry.id === id);
  return service ? enrichService(service) : undefined;
}
